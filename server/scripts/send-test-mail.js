/**
 * Sends a sample application e-mail (with a tiny PDF attached) so you can check the
 * mailbox layout without filling the form.   Usage:  cd server && npm run test:mail
 */
import '../src/env.js'
import { sendMail, verifyTransport } from '../src/mailer.js'
import { applicationEmail, makeReference } from '../src/templates.js'

const ok = await verifyTransport()
if (!ok) {
  console.error('SMTP verification failed — check server/.env')
  process.exit(1)
}

const pdf = Buffer.from(
  '%PDF-1.4\n1 0 obj<</Type/Catalog/Pages 2 0 R>>endobj\n2 0 obj<</Type/Pages/Kids[3 0 R]/Count 1>>endobj\n3 0 obj<</Type/Page/Parent 2 0 R/MediaBox[0 0 200 100]>>endobj\ntrailer<</Root 1 0 R>>\n%%EOF',
)

const reference = makeReference('NV')
const info = await sendMail(
  applicationEmail({
    reference,
    ip: '127.0.0.1',
    files: { resume: { buffer: pdf, ext: 'pdf', mimetype: 'application/pdf' }, coverLetterFile: null },
    data: {
      applicationType: 'Job',
      position: 'Software Engineer',
      positionOther: '',
      vertical: 'IT',
      preferredLocation: 'Bilaspur',
      availability: '30 days',
      startDate: '',
      fullName: 'Test Candidate',
      email: process.env.SMTP_USER || 'test@example.com',
      phone: '+91 98765 43210',
      city: 'Raipur',
      linkedin: 'https://www.linkedin.com/in/example',
      qualification: "Bachelor's degree (B.E. / B.Tech / B.Sc / B.Com / BBA / other)",
      institution: 'NIT Raipur',
      fieldOfStudy: 'Computer Science',
      graduationYear: '2023',
      experience: '1 - 3 years',
      employer: 'Example Pvt Ltd',
      currentRole: 'Developer',
      skills: 'TypeScript, React, Node.js, PostgreSQL',
      coverLetter: 'This is a test message generated by send-test-mail.js.',
      referral: 'Nova Ventures website',
      notes: '',
      consent: 'true',
      declaration: 'true',
    },
  }),
)
console.log('Sent:', info.messageId, '→', process.env.MAIL_TO, 'reference', reference)
process.exit(0)
